const CACHE = 'marbles-3b96cabfb85862a6';

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(Promise.all([
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith('marbles-') && key !== CACHE).map((key) => caches.delete(key)))),
    self.clients.claim(),
  ]));
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || /^\/(api|auth|callback)(\/|$)/.test(url.pathname) || url.pathname.startsWith('/.well-known/')) return;
  // Menus are generated by HTML + JavaScript. Never put documents, scripts,
  // styles, manifests, or source maps in the worker cache.
  if (request.mode === 'navigate' || /\.(?:html?|m?js|css|map|webmanifest)$/i.test(url.pathname) || url.pathname === '/') return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    try {
      const fresh = await fetch(request, { cache: 'no-store' });
      if (fresh.ok) await cache.put(request, fresh.clone());
      return fresh;
    } catch (error) {
      const saved = await cache.match(request, { ignoreSearch: false });
      if (saved) return saved;
      throw error;
    }
  })());
});
